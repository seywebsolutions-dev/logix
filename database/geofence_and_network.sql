-- ------------------------------------------------------------
-- 7. Admin management of worksites & networks
-- ------------------------------------------------------------
create or replace function public.admin_save_worksite(
  p_token uuid, p_id bigint, p_name text,
  p_lat double precision, p_lng double precision, p_radius integer,
  p_require_network boolean, p_require_location boolean, p_is_active boolean
) returns public.worksites
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_row public.worksites;
begin
  perform public._require_session(p_token, true);

  if p_id is null then
    insert into public.worksites (name, latitude, longitude, radius_meters, require_network, require_location, is_active)
    values (p_name, p_lat, p_lng, coalesce(p_radius, 200), coalesce(p_require_network, true), coalesce(p_require_location, true), coalesce(p_is_active, true))
    returning * into v_row;
  else
    update public.worksites set
      name = p_name, latitude = p_lat, longitude = p_lng,
      radius_meters = coalesce(p_radius, 200),
      require_network = coalesce(p_require_network, true),
      require_location = coalesce(p_require_location, true),
      is_active = coalesce(p_is_active, true)
    where id = p_id
    returning * into v_row;
  end if;

  return v_row;
end;
$$;
revoke all on function public.admin_save_worksite(uuid, bigint, text, double precision, double precision, integer, boolean, boolean, boolean) from public;
grant execute on function public.admin_save_worksite(uuid, bigint, text, double precision, double precision, integer, boolean, boolean, boolean) to anon, authenticated;

create or replace function public.admin_add_network(p_token uuid, p_worksite_id bigint, p_cidr text, p_label text)
returns public.worksite_networks
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_row public.worksite_networks;
  v_cidr cidr;
begin
  perform public._require_session(p_token, true);
  begin
    -- A bare address like 41.20.30.40 becomes a /32 host route.
    v_cidr := p_cidr::cidr;
  exception when others then
    raise exception 'Not a valid IP address or CIDR range: %', p_cidr;
  end;

  insert into public.worksite_networks (worksite_id, cidr, label)
  values (p_worksite_id, v_cidr, p_label)
  returning * into v_row;
  return v_row;
end;
$$;
revoke all on function public.admin_add_network(uuid, bigint, text, text) from public;
grant execute on function public.admin_add_network(uuid, bigint, text, text) to anon, authenticated;

create or replace function public.admin_delete_network(p_token uuid, p_id bigint) returns void
language plpgsql security definer set search_path = public, extensions as $$
begin
  perform public._require_session(p_token, true);
  delete from public.worksite_networks where id = p_id;
end;
$$;
revoke all on function public.admin_delete_network(uuid, bigint) from public;
grant execute on function public.admin_delete_network(uuid, bigint) to anon, authenticated;

