-- ============================================================
--  LOGIX FOR STA SEYCHELLES — ON-SITE CLOCK-IN ENFORCEMENT
-- ============================================================
--  Run AFTER harden_auth_and_rls.sql
--
--  GOAL: stop staff clocking in from home.
--
--  WHY NOT "CHECK THE WIFI NAME": browsers cannot read the SSID of
--  the network the device is on. There is no web API for it, on any
--  browser, by design (privacy). Only a native iOS/Android app can.
--  So we verify the two things a browser CAN prove, server-side:
--
--    1. NETWORK  — the device's public IP must fall inside a CIDR
--                  range registered for the campus. Someone on the
--                  STA WiFi shares the academy's public IP; someone
--                  at home does not. This is the practical
--                  equivalent of "must be on the office WiFi".
--    2. LOCATION — GPS coordinates must be inside a geofence.
--
--  Both are checked in the database, not the browser, so editing the
--  page in devtools cannot bypass them.
--
--  IMPORTANT ON IP SPOOFING: a client CAN send its own
--  X-Forwarded-For header. Supabase does not overwrite it — it
--  APPENDS the true client IP. So the spoofed value lands on the
--  LEFT and the trustworthy one is the RIGHTMOST entry. Most code
--  samples online read the leftmost entry, which is exactly the
--  spoofable one. We read the rightmost, and prefer Cloudflare's
--  cf-connecting-ip when present (the edge sets it; clients cannot).
-- ============================================================

-- ------------------------------------------------------------
-- 1. Worksites + their registered networks
-- ------------------------------------------------------------
create table if not exists public.worksites (
  id bigint generated by default as identity primary key,
  name text not null,
  latitude double precision,
  longitude double precision,
  radius_meters integer not null default 200,
  require_network boolean not null default true,
  require_location boolean not null default true,
  is_active boolean not null default true,
  created_at timestamp with time zone not null default now()
);

create table if not exists public.worksite_networks (
  id bigint generated by default as identity primary key,
  worksite_id bigint not null references public.worksites(id) on delete cascade,
  cidr cidr not null,
  label text,
  created_at timestamp with time zone not null default now()
);

-- Every clock attempt, allowed or denied. This is the fraud record.
create table if not exists public.clock_events (
  id bigint generated by default as identity primary key,
  employee_id bigint references public.employees(id) on delete set null,
  action text not null,
  allowed boolean not null,
  denial_reason text,
  ip inet,
  latitude double precision,
  longitude double precision,
  accuracy_meters double precision,
  distance_meters double precision,
  user_agent text,
  created_at timestamp with time zone not null default now()
);
create index if not exists idx_clock_events_created on public.clock_events (created_at desc);
create index if not exists idx_clock_events_allowed on public.clock_events (allowed, created_at desc);

-- Record where each clock punch actually happened
alter table public.attendance
  add column if not exists clock_in_ip inet,
  add column if not exists clock_out_ip inet,
  add column if not exists clock_in_lat double precision,
  add column if not exists clock_in_lng double precision,
  add column if not exists clock_out_lat double precision,
  add column if not exists clock_out_lng double precision;

alter table public.worksites enable row level security;
alter table public.worksite_networks enable row level security;
alter table public.clock_events enable row level security;

revoke all on public.worksites from anon, authenticated;
revoke all on public.worksite_networks from anon, authenticated;
revoke all on public.clock_events from anon, authenticated;
-- Read access only, and only through explicit grants; all writes go
-- through the SECURITY DEFINER functions below.
