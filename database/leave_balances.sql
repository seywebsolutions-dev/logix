-- ------------------------------------------------------------
-- 3. Per-employee overrides
-- ------------------------------------------------------------
create table if not exists public.leave_entitlements (
  id            bigint generated by default as identity primary key,
  employee_id   bigint not null references public.employees(id) on delete cascade,
  leave_type_id bigint not null references public.leave_types(id) on delete cascade,
  year          int not null,
  days_entitled numeric(5,1) not null check (days_entitled >= 0),
  note          text,
  created_at    timestamp with time zone default timezone('utc'::text, now()) not null,
  unique (employee_id, leave_type_id, year)
);

comment on table public.leave_entitlements is
  'Overrides leave_types.max_days_per_year for one person in one year. Absent row means the type default applies.';

create index if not exists leave_entitlements_lookup
  on public.leave_entitlements (employee_id, year);


-- ------------------------------------------------------------
-- 4. Working-day counter
-- ------------------------------------------------------------
-- Counts Mon-Fri days between two dates inclusive, skipping public holidays.
-- A half day counts as 0.5 and is only meaningful on a single-day request.
create or replace function public.count_leave_days(
  p_start date, p_end date, p_half_day boolean default false
) returns numeric
language sql stable security definer set search_path = public, extensions as $$
  select case
    when p_start is null or p_end is null or p_end < p_start then 0
    when coalesce(p_half_day, false) and p_start = p_end then 0.5
    else (
      select count(*)::numeric
      from generate_series(p_start, p_end, interval '1 day') as d(day)
      where extract(isodow from d.day) < 6
        and not exists (
          select 1 from public.public_holidays h
          where h.holiday_date = d.day::date
        )
    )
  end;
$$;


-- ------------------------------------------------------------
-- 5. Balance calculation
-- ------------------------------------------------------------
-- Returns one row per capped leave type: entitled, used, remaining.
-- "Used" counts approved requests only; pending is reported separately so
-- staff can see what is still awaiting a decision.
create or replace function public._leave_balances(p_employee_id bigint, p_year int)
returns table (
  leave_code   text,
  leave_name   text,
  color        text,
  entitled     numeric,
  used         numeric,
  pending      numeric,
  remaining    numeric
)
language sql stable security definer set search_path = public, extensions as $$
  select
    lt.code,
    lt.name,
    lt.color,
    ent.days                                        as entitled,
    coalesce(tally.approved, 0)                     as used,
    coalesce(tally.pending, 0)                      as pending,
    greatest(ent.days - coalesce(tally.approved, 0), 0) as remaining
  from public.leave_types lt
  cross join lateral (
    select coalesce(
      (select le.days_entitled
         from public.leave_entitlements le
        where le.employee_id = p_employee_id
          and le.leave_type_id = lt.id
          and le.year = p_year),
      lt.max_days_per_year
    )::numeric as days
  ) ent
  left join lateral (
    select
      sum(public.count_leave_days(lr.start_date, lr.end_date, lr.is_half_day))
        filter (where lr.status = 'approved') as approved,
      sum(public.count_leave_days(lr.start_date, lr.end_date, lr.is_half_day))
        filter (where lr.status = 'pending')  as pending
    from public.leave_requests lr
    where lr.employee_id = p_employee_id
      and lr.leave_type_id = lt.id
      and extract(year from lr.start_date) = p_year
  ) tally on true
  where lt.is_active
    and ent.days is not null      -- uncapped types carry no balance
  order by lt.name;
$$;


-- Employee-facing: my own balances for a given year (defaults to this year).
create or replace function public.my_leave_balances(p_token uuid, p_year int default null)
returns table (
  leave_code text, leave_name text, color text,
  entitled numeric, used numeric, pending numeric, remaining numeric
)
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_session record;
  v_year int := coalesce(p_year, extract(year from current_date)::int);
begin
  select * into v_session from public._require_session(p_token, false);
  return query select * from public._leave_balances(v_session.employee_id, v_year);
end;
$$;


