-- ------------------------------------------------------------
-- 6. Enforce the balance when a request is submitted
-- ------------------------------------------------------------
-- Replaces the version in harden_auth_and_rls.sql. Same signature, so the
-- front end needs no change to keep working - it just gets a clear error
-- instead of silently over-drawing.
create or replace function public.submit_leave_request(
  p_token uuid, p_leave_code text, p_start date, p_end date,
  p_reason text, p_half_day boolean
) returns public.leave_requests
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_session       record;
  v_type          record;
  v_row           public.leave_requests;
  v_days          numeric;
  v_remaining     numeric;
  v_pending       numeric;
  v_year          int;
begin
  select * into v_session from public._require_session(p_token, false);

  select id, name, max_days_per_year into v_type
    from public.leave_types where code = p_leave_code and is_active;
  if v_type.id is null then
    raise exception 'Unknown leave type';
  end if;

  if p_start is null or p_end is null then
    raise exception 'A start and end date are both required';
  end if;
  if p_end < p_start then
    raise exception 'The end date cannot be before the start date';
  end if;
  if coalesce(p_half_day, false) and p_start <> p_end then
    raise exception 'A half day must start and end on the same date';
  end if;

  v_days := public.count_leave_days(p_start, p_end, p_half_day);
  if v_days = 0 then
    raise exception 'That range contains no working days - it is all weekend or public holiday';
  end if;

  -- Overlap guard: two approved or pending requests on the same days is
  -- almost always a double submission rather than an intention.
  if exists (
    select 1 from public.leave_requests lr
    where lr.employee_id = v_session.employee_id
      and lr.status in ('pending', 'approved')
      and lr.start_date <= p_end
      and lr.end_date   >= p_start
  ) then
    raise exception 'You already have a leave request covering some of those dates';
  end if;

  -- Balance check, for capped types only.
  if v_type.max_days_per_year is not null then
    v_year := extract(year from p_start)::int;

    select b.remaining, b.pending into v_remaining, v_pending
      from public._leave_balances(v_session.employee_id, v_year) b
     where b.leave_code = p_leave_code;

    if coalesce(v_remaining, 0) - coalesce(v_pending, 0) < v_days then
      raise exception
        '% days requested but only % left for % in % (% already awaiting approval)',
        v_days,
        greatest(coalesce(v_remaining, 0) - coalesce(v_pending, 0), 0),
        v_type.name, v_year, coalesce(v_pending, 0);
    end if;
  end if;

  insert into public.leave_requests
    (employee_id, leave_type_id, start_date, end_date, reason, is_half_day)
  values
    (v_session.employee_id, v_type.id, p_start, p_end, p_reason, coalesce(p_half_day, false))
  returning * into v_row;

  return v_row;
end;
$$;


-- ------------------------------------------------------------
-- 7. Let an administrator set an entitlement
-- ------------------------------------------------------------
create or replace function public.admin_set_entitlement(
  p_token uuid, p_employee_id bigint, p_leave_code text,
  p_year int, p_days numeric, p_note text default null
) returns void
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_session   record;
  v_type_id   bigint;
  v_actor     text;
  v_target    text;
begin
  select * into v_session from public._require_session(p_token, true);

  select id into v_type_id from public.leave_types where code = p_leave_code;
  if v_type_id is null then
    raise exception 'Unknown leave type';
  end if;
  if p_days < 0 then
    raise exception 'Entitlement cannot be negative';
  end if;

  insert into public.leave_entitlements (employee_id, leave_type_id, year, days_entitled, note)
  values (p_employee_id, v_type_id, p_year, p_days, p_note)
  on conflict (employee_id, leave_type_id, year)
  do update set days_entitled = excluded.days_entitled, note = excluded.note;

  select full_name into v_actor  from public.employees where id = v_session.employee_id;
  select full_name into v_target from public.employees where id = p_employee_id;

  insert into public.audit_log (actor_id, actor_name, action_type, target_employee, details)
  values (v_session.employee_id, coalesce(v_actor, 'Admin'), 'SET_ENTITLEMENT',
          coalesce(v_target, ''),
          format('%s set to %s days for %s', p_leave_code, p_days, p_year));
end;
$$;


-- ------------------------------------------------------------
-- 8. Holiday management
-- ------------------------------------------------------------
create or replace function public.list_public_holidays(p_token uuid, p_year int default null)
returns table (id bigint, holiday_date date, name text)
language plpgsql security definer set search_path = public, extensions as $$
declare
  v_session record;
  v_year int := coalesce(p_year, extract(year from current_date)::int);
begin
  select * into v_session from public._require_session(p_token, false);
  return query
    select h.id, h.holiday_date, h.name
      from public.public_holidays h
     where extract(year from h.holiday_date) = v_year
     order by h.holiday_date;
end;
$$;

create or replace function public.admin_add_holiday(p_token uuid, p_date date, p_name text)
returns void
language plpgsql security definer set search_path = public, extensions as $$
declare v_session record;
begin
  select * into v_session from public._require_session(p_token, true);
  insert into public.public_holidays (holiday_date, name)
  values (p_date, p_name)
  on conflict (holiday_date) do update set name = excluded.name;
end;
$$;

create or replace function public.admin_delete_holiday(p_token uuid, p_id bigint)
returns void
language plpgsql security definer set search_path = public, extensions as $$
declare v_session record;
begin
  select * into v_session from public._require_session(p_token, true);
  delete from public.public_holidays where id = p_id;
end;
$$;


