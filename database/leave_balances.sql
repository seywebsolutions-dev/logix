-- ============================================================
--  LOGIX — LEAVE BALANCES & PUBLIC HOLIDAYS
--  Run this AFTER password_security.sql (migration 7 of 7).
--
--  Before this file, approving leave was blind: there was no record
--  of how many days anyone was entitled to or had already used.
--  This adds entitlements, a working-day counter that skips weekends
--  and public holidays, and a balance check inside the submit path so
--  the database refuses an over-drawn request rather than trusting
--  the browser to hide the button.
-- ============================================================

